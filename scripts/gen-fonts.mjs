// Bundles the PDF fonts as base64 so serverless functions never depend on file tracing.
import fs from 'fs';
const fonts = {
  caveat: 'caveat/files/caveat-latin-500-normal.woff',
  caveatBold: 'caveat/files/caveat-latin-700-normal.woff',
  serif: 'young-serif/files/young-serif-latin-400-normal.woff',
  mono: 'courier-prime/files/courier-prime-latin-400-normal.woff',
  monoBold: 'courier-prime/files/courier-prime-latin-700-normal.woff',
  script: 'homemade-apple/files/homemade-apple-latin-400-normal.woff',
};
let out = '// Generated by scripts/gen-fonts.mjs. Do not edit.\n';
for (const [k, p] of Object.entries(fonts)) {
  out += `export const ${k} = "${fs.readFileSync('node_modules/@fontsource/' + p).toString('base64')}";\n`;
}
fs.writeFileSync('lib/fonts.generated.ts', out);
console.log('wrote', (out.length / 1024).toFixed(0), 'KB');
